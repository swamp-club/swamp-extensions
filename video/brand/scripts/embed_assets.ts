/**
 * Regenerates extensions/models/_lib/brand_assets.ts from assets/brand/.
 * Run from video/brand after changing an asset:
 *
 *   deno run --allow-read --allow-write scripts/embed_assets.ts
 *
 * assets_test.ts fails while the module and the sources disagree.
 *
 * @module
 */

import { ASSET_FILES, dataUri } from "../extensions/models/_lib/assets.ts";

const root = new URL("../", import.meta.url).pathname;
const lines = [
  "// Generated by scripts/embed_assets.ts from assets/brand/; do not edit.",
  "// The fonts are under the SIL Open Font License 1.1 (FONTS-LICENSE.txt).",
  "",
  "export const EMBEDDED: Record<string, string> = {",
];
for (const file of ASSET_FILES) {
  const bytes = await Deno.readFile(`${root}assets/brand/${file}`);
  lines.push(`  "${file}":\n    "${dataUri(file, bytes)}",`);
}
lines.push("};", "");
await Deno.writeTextFile(
  `${root}extensions/models/_lib/brand_assets.ts`,
  lines.join("\n"),
);
